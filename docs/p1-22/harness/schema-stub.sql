-- P1-22 scratch schema (subset of live tables). Not a full production dump.
CREATE EXTENSION IF NOT EXISTS pgcrypto;
CREATE SCHEMA IF NOT EXISTS ops;
CREATE SCHEMA IF NOT EXISTS auth;
CREATE SCHEMA IF NOT EXISTS public;

-- Roles that exist on live Supabase; created here so GRANT/REVOKE in the
-- migration can run on a scratch PGlite/Postgres. Not part of the live migration.
DO $$ BEGIN
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'anon') THEN
    CREATE ROLE anon;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'authenticated') THEN
    CREATE ROLE authenticated;
  END IF;
  IF NOT EXISTS (SELECT 1 FROM pg_roles WHERE rolname = 'service_role') THEN
    CREATE ROLE service_role;
  END IF;
END $$;


CREATE TABLE IF NOT EXISTS auth.users (
  id uuid PRIMARY KEY,
  email text,
  raw_app_meta_data jsonb DEFAULT '{}'::jsonb
);

CREATE OR REPLACE FUNCTION auth.uid()
RETURNS uuid
LANGUAGE sql
STABLE
AS $$
  SELECT NULLIF(current_setting('request.jwt.claim.sub', true), '')::uuid;
$$;

CREATE TABLE IF NOT EXISTS public.users (
  id uuid PRIMARY KEY,
  email text
);

CREATE OR REPLACE FUNCTION public.is_test_account(p_email text)
RETURNS boolean
LANGUAGE sql
STABLE
AS $$
  SELECT lower(coalesce(p_email, '')) ~ '^jim\+romrx-[a-z0-9._-]+@romrx\.io$'
     AND EXISTS (
       SELECT 1 FROM auth.users u
       WHERE lower(u.email) = lower(p_email)
         AND u.raw_app_meta_data->>'test_fixture' = 'true'
     );
$$;

CREATE TABLE IF NOT EXISTS public.assessments (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid,
  assessed_at timestamptz
);

CREATE TABLE IF NOT EXISTS public.protocol_sessions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL,
  session_date date,
  protocol_day text,
  logged_at timestamptz DEFAULT now(),
  sport text
);
CREATE UNIQUE INDEX IF NOT EXISTS protocol_sessions_user_date
  ON public.protocol_sessions (user_id, session_date);

CREATE TABLE IF NOT EXISTS public.protocol_completions (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid NOT NULL,
  assessment_id uuid,
  exercise_id uuid,
  joint text,
  completed_at timestamptz NOT NULL DEFAULT now(),
  sets_completed integer,
  reps_completed integer,
  difficulty_rating integer,
  pain_rating integer,
  notes text
);

CREATE TABLE IF NOT EXISTS public.product_events (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  user_id uuid,
  anon_id text,
  session_id text,
  event text,
  props jsonb DEFAULT '{}'::jsonb,
  sport text,
  source text,
  path text,
  created_at timestamptz DEFAULT now()
);

CREATE TABLE IF NOT EXISTS public.notification_preferences (
  id uuid PRIMARY KEY DEFAULT gen_random_uuid(),
  user_id uuid,
  email_reminders boolean,
  push_reminders boolean,
  reminder_time text,
  timezone text,
  push_subscription jsonb,
  updated_at timestamptz DEFAULT now(),
  retest_reminders boolean,
  weekly_digest boolean,
  retest_opt_in_at timestamptz,
  protocol_opt_in_at timestamptz,
  digest_opt_in_at timestamptz
);

CREATE TABLE IF NOT EXISTS ops.base_onboarding_funnel (
  user_id uuid PRIMARY KEY,
  is_test boolean DEFAULT false,
  first_assessment_at timestamptz
);
